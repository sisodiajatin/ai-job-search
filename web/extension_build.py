"""Write extension/collect.js from the engine's COLLECT_JS so the extension and the Playwright
filler read pages with the same code. Run after editing engine/fields.py."""

from pathlib import Path

from apply_forms.engine.fields import COLLECT_JS

OUT = Path(__file__).resolve().parent / "extension" / "collect.js"


def render() -> str:
    return "// Generated by web/extension/build.py from apply_forms/engine/fields.py. Do not edit.\nwindow.__jdCollect = " + COLLECT_JS.strip() + ";\n"


if __name__ == "__main__":
    OUT.write_text(render(), encoding="utf-8")
    print("wrote", OUT)
